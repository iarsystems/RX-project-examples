void updateVNC(int16_t x, int16_t y, int16_t dx, int16_t dy, uint8_t index)
{
  /* Make sure the rectangle being sent isn't larger than screen */
  if (x + dx >= X_SIZE)
  {
    dx = X_SIZE - x - 1;
  }
  if (y + dy >= Y_SIZE)
  {
    dy = Y_SIZE - y - 1;
  }
  
  /* Populate the VNC struct array and set 'valid' flag */
  if (vncBall[index].valid == 0)
  {
    vncBall[index].x      =  x;
    vncBall[index].y      =  y;
    vncBall[index].dx     =  dx;
    vncBall[index].dy     =  dy;
    vncBall[index].valid  =  1;

  }
 }
