#define FLASHDISK_MEDIATYPE              0xF8u   /* Fixed media */

#define FLASHDISK_SIGNATURE              0xAA55u

#define FLASHDISK_CLSTSIZE               0x01u
#define FLASHDISK_FATNUM                 0x02u

/*
    If the number of data areas of clusters is smaller
    than that of value 4085(4096-11), it is FAT12.
    If the number of data areas of clusters is smaller
    than that of value 65525(65536-11), it is FAT16.
    Otherwise it is FAT32.
*/

#if FLASHDISK_TOTALSECT < 4096
        #define FLASHDISK_FATLENGTH      341ul   /* FAT12 */
#else
    #if FLASHDISK_TOTALSECT < 65536
        #define FLASHDISK_FATLENGTH      256ul   /* FAT16 */
    #else
        #define FLASHDISK_FATLENGTH      128ul   /* FAT32 */
    #endif
#endif

#define FLASHDISK_FATSIZE   (((FLASHDISK_TOTALSECT - 8) / FLASHDISK_FATLENGTH) + 1)

#define FLASHDISK_ROOTTOP   (((FLASHDISK_FATSIZE  * FLASHDISK_FATNUM + 1) / 8 + 1 ) * 8)
#define USB_MEDIA_FATTOP  (FLASHDISK_ROOTTOP - (FLASHDISK_FATSIZE * FLASHDISK_FATNUM))

#define USB_MEDIA_ROOTSIZE              1ul


