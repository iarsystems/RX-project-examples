void main(void)
{
    R_MAIN_UserInit();
    /* Start user code. Do not edit comment generated here */
    
    /* set old status to some arbitary value other tehn 0 or 1 */
    old_voltage_status = 0xFF;
    Clear_Display();
    DisplayCenter(0, "Voltage Detect");
    
    /* start toggling the LEds */
    R_CMT1_Start();

    R_LVD1_Start();
    while (1)
    {
        current_voltage_status = getVoltageStatus() ;
        if (current_voltage_status != old_voltage_status)
        {
            if (current_voltage_status)
            {
                DisplayCenter(3, " Vcc > Vdet ");
                R_LVD1_Start();
            }
            else
            {
                DisplayCenter(3, " Vcc < Vdet ");
                R_LVD1_Start();
            }
            old_voltage_status = current_voltage_status;
        }
    }
    /* End user code. Do not edit comment generated here */
}
