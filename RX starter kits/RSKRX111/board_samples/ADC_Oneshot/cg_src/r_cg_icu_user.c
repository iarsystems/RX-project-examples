/*******************************************************************************
* Function Name : InitialiseSwitches
* Description   : Sets the switch monitoring variables and starts the
*                 switch IRQs.
*                 Points the keypress and release function pointers to the
*                 correct handler functions
* Argument      : none
* Return value  : none
*******************************************************************************/
void Init_Switches(void)
{
    /* Reset the switch flag */
    g_switch_flag = 0x00;

    /* Reset the switch standby ready flag */
    g_switch_standby_ready = 0x1;

    /* reset the switch fault count */
    g_switch_faults_detected = 0;

    /* Start IRQ0 to monitor SW1 */
    R_ICU_IRQ0_Start();
    /* Start IRQ1 to monitor SW2 */
    R_ICU_IRQ1_Start();
    /* Start IRQ4 to monitor SW3 */
    R_ICU_IRQ4_Start();

}
/******************************************************************************
* End of function InitialiseSwitches
******************************************************************************/

