/*******************************************************************************************************************//**
 * init_cpscu() sets the security attributes.
 **********************************************************************************************************************/
void init_cpscu(void) {
    R_CPSCU->BUSSARA_b.BUSSA0 = 1;
    R_CPSCU->BUSSARB_b.BUSSB0 = 1;
    R_CPSCU->BUSSARC_b.BUSSC0 = 1;

    /* ICU Security Attribution Register Settings */
    /* SWINT, IRQ0 only */
    R_CPSCU_Swint_Irq0_Set(R_PZ_NONE_SECURE);
}

/*******************************************************************************************************************//**
 * main() is generated by the RX Configuration editor and is used to generate threads if an RTOS is used.  This function
 * is called by main() when no RTOS is used.
 **********************************************************************************************************************/
#ifdef __ICCRX__

#pragma section=".exvectors" __data32
#pragma section=".rvectors" __data32
static uint32_t *exvectors_secure = __section_begin(".exvectors");
static uint32_t *rvectors_secure = __section_begin(".rvectors");
#endif

int main(void)
{
    /* TODO: add your own code here */
//    uint32_t *ns_reset_address = (uint32_t *)gp_start_of_nonsecure_flash;
#ifdef __ICCRX__
  // Setup TR vector tables
    __asm volatile (
        "mvtc    %0, extb      \n"    /* EXCEPTION VECTOR ADDRESS    */
	    : : "r" (exvectors_secure)
	);
    /* setup secure intb */
	__asm volatile (
	    "mvtc    %0, intb      \n"    /* INTERRUPT VECTOR ADDRESS  definition    */
        : : "r" (rvectors_secure)
    );
#endif
  
    initialize_pz();
    init_cpscu();

    /* PC, PSW : I = 0(Disable Interrupt), U = 0(ISP), PM = 0(Super), IPL = 0 */
    #if defined(__CCRX__)
    InitNSContext(0x0200C000, 0x00000000);
#elif defined(__GNUC__)
//    InitNSContext((uint32_t)(ns_reset_address), 0x00000000);
    InitNSContext((uint32_t)(*gp_start_of_nonsecure_flash), 0x00000000);
#elif defined(__ICCRX__)
    InitNSContext(0x0200C000, 0x00000000);
#endif

    /* Secureの呼び出し */
    StartSecure((uint32_t)pre_main_sec, 0x00000000);

    while(1);

    R_CPSCU_Swint_Irq0_Set(R_PZ_SECURE);
    R_SYSTEM->PRCR = 0xA502;

    return 1;
}

/*******************************************************************************************************************//**
 * root_world_check_error() is used when a world check error occurs.
 **********************************************************************************************************************/
void root_world_check_error(void)
{
    while (1)
    {
#if defined(__CCRX__)
        nop();
#elif defined(__GNUC__)
        __asm("nop");
#elif defined(__ICCRX__)
    __no_operation();
#endif
    }
}



