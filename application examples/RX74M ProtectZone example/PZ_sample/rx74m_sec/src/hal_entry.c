/*******************************************************************************************************************//**
 * InitNSContext() initializes the CPU context information for Non-Secure.
 **********************************************************************************************************************/
void InitNSContext(uint32_t entry, uint32_t psw) {
    NSContext.pc = entry;
    NSContext.psw = psw;
}

/*******************************************************************************************************************//**
 * initialize_pz() is the initialization process to enable ProtectZone.
 **********************************************************************************************************************/
static void initialize_pz(void)
{
    /* Protected zone enabled */
    R_ProtectZone_Open();

    /* IVC Register setting(IVC.NSIC = 1) */
    /* Interrupts of level 15 or lower can only be accepted when the PSW.I bit is “1”. */
    set_ivc(0x01000000);
}

